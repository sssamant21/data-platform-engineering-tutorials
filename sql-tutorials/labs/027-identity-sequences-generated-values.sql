BEGIN;
SET LOCAL statement_timeout = '10s';
SET LOCAL lock_timeout = '2s';
SET LOCAL idle_in_transaction_session_timeout = '30s';
DO $guard$
BEGIN
 IF current_setting('server_version_num')::integer NOT BETWEEN 180000 AND 189999
    OR current_database() <> 'sql_tutorials' OR pg_is_in_recovery() THEN
   RAISE EXCEPTION 'Requires independently isolated PostgreSQL 18 primary sql_tutorials';
 END IF;
END
$guard$;

CREATE TEMP TABLE ch027_orders (
 order_id bigint GENERATED ALWAYS AS IDENTITY (START WITH 100) PRIMARY KEY,
 order_code text NOT NULL UNIQUE
) ON COMMIT DROP;

INSERT INTO ch027_orders (order_code) VALUES ('SYN-A'),('SYN-B');
-- Expected IDs: 100, 101.
DO $negative$
DECLARE rejected boolean := false;
BEGIN
 BEGIN
  INSERT INTO ch027_orders (order_id,order_code) VALUES (999,'SYN-REJECT');
 EXCEPTION WHEN SQLSTATE '428C9' THEN rejected := true;
 END;
 IF NOT rejected THEN
  RAISE EXCEPTION 'ALWAYS identity failed to reject explicit ID';
 END IF;
END
$negative$;

INSERT INTO ch027_orders (order_id,order_code)
 OVERRIDING SYSTEM VALUE VALUES (999,'SYN-IMPORT');
INSERT INTO ch027_orders (order_code) VALUES ('SYN-C');
SELECT order_id,order_code FROM ch027_orders ORDER BY order_id;
-- Expected: (100,SYN-A),(101,SYN-B),(102,SYN-C),(999,SYN-IMPORT).

CREATE TEMP TABLE ch027_default (
 event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_code text NOT NULL
) ON COMMIT DROP;
INSERT INTO ch027_default (event_id,event_code) VALUES (500,'SYN-EXPLICIT');
INSERT INTO ch027_default (event_code) VALUES ('SYN-AUTO');
-- Expected: explicit ID 500; generated ID 1.
DO $dup$
DECLARE rejected boolean := false;
BEGIN
 BEGIN
  INSERT INTO ch027_default (event_id,event_code) VALUES (500,'SYN-DUP');
 EXCEPTION WHEN unique_violation THEN rejected := true;
 END;
 IF NOT rejected THEN RAISE EXCEPTION 'Duplicate primary key was not rejected'; END IF;
END
$dup$;

CREATE TEMP TABLE ch027_lines (
 order_id bigint NOT NULL,
 quantity integer NOT NULL CHECK (quantity > 0),
 unit_price numeric(10,2) NOT NULL CHECK (unit_price >= 0),
 line_total numeric(12,2) GENERATED ALWAYS AS (quantity * unit_price) STORED
) ON COMMIT DROP;
INSERT INTO ch027_lines (order_id,quantity,unit_price)
 VALUES (100,2,12.50),(101,3,7.25);
SELECT order_id,quantity,unit_price,line_total FROM ch027_lines ORDER BY order_id;
-- Expected: (100,2,12.50,25.00), (101,3,7.25,21.75).

CREATE TEMP SEQUENCE ch027_counter START WITH 10 INCREMENT BY 5;
SELECT nextval('pg_temp.ch027_counter'::regclass) AS first_value;
-- Expected: 10.
SELECT nextval('pg_temp.ch027_counter'::regclass) AS second_value;
-- Expected: 15. Sequence allocation is NOT rolled back, even though objects here are temporary.

DO $assert$
DECLARE order_ids bigint[]; default_ids bigint[]; line_total numeric; line_count bigint; seq_last bigint;
BEGIN
 SELECT array_agg(order_id ORDER BY order_id) INTO order_ids FROM ch027_orders;
 SELECT array_agg(event_id ORDER BY event_id) INTO default_ids FROM ch027_default;
 SELECT SUM(l.line_total),COUNT(*) INTO line_total,line_count FROM ch027_lines AS l;
 SELECT last_value INTO seq_last FROM ch027_counter;
 IF order_ids IS DISTINCT FROM ARRAY[100,101,102,999]::bigint[]
    OR default_ids IS DISTINCT FROM ARRAY[1,500]::bigint[]
    OR line_total IS DISTINCT FROM 46.75::numeric
    OR line_count <> 2 OR seq_last <> 15 THEN
   RAISE EXCEPTION 'Chapter 027 assertions failed: orders %, default %, total %, lines %, sequence %',
    order_ids,default_ids,line_total,line_count,seq_last;
 END IF;
 RAISE NOTICE 'Chapter 027 synthetic assertions passed';
END
$assert$;
ROLLBACK;
