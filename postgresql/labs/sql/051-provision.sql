\set ON_ERROR_STOP on
-- Run ONLY in dedicated ch051_lab database as lab administrator.
DO $$
BEGIN
 IF current_database() <> 'ch051_lab' THEN
   RAISE EXCEPTION 'Refusing to run outside ch051_lab';
 END IF;
 IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname IN
  ('ch051_owner','ch051_reader_group','ch051_writer_group','ch051_reader','ch051_writer')) THEN
   RAISE EXCEPTION 'Chapter 051 role collision; refusing to modify existing roles';
 END IF;
END $$;
CREATE ROLE ch051_owner NOLOGIN;
CREATE ROLE ch051_reader_group NOLOGIN;
CREATE ROLE ch051_writer_group NOLOGIN;
CREATE ROLE ch051_reader LOGIN NOINHERIT;
CREATE ROLE ch051_writer LOGIN NOINHERIT;
GRANT ch051_reader_group TO ch051_reader WITH INHERIT TRUE, SET FALSE;
GRANT ch051_writer_group TO ch051_writer WITH INHERIT TRUE, SET FALSE;
CREATE SCHEMA ch051 AUTHORIZATION ch051_owner;
GRANT CONNECT ON DATABASE ch051_lab TO ch051_reader, ch051_writer;
GRANT USAGE ON SCHEMA ch051 TO ch051_reader_group,ch051_writer_group;
SET ROLE ch051_owner;
CREATE TABLE ch051.events(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, payload text NOT NULL);
CREATE TABLE ch051.future_events(id bigint PRIMARY KEY, payload text NOT NULL);
RESET ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA ch051 TO ch051_reader_group;
GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA ch051 TO ch051_writer_group;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA ch051 TO ch051_writer_group;
ALTER DEFAULT PRIVILEGES FOR ROLE ch051_owner IN SCHEMA ch051 GRANT SELECT ON TABLES TO ch051_reader_group;
ALTER DEFAULT PRIVILEGES FOR ROLE ch051_owner IN SCHEMA ch051 GRANT SELECT,INSERT,UPDATE,DELETE ON TABLES TO ch051_writer_group;
ALTER DEFAULT PRIVILEGES FOR ROLE ch051_owner IN SCHEMA ch051 GRANT USAGE,SELECT ON SEQUENCES TO ch051_writer_group;

SET ROLE ch051_owner;
CREATE TABLE ch051.after_default_grants(id bigint PRIMARY KEY,payload text NOT NULL);
RESET ROLE;
