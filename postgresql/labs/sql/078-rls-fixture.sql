-- Chapter 078 lab fixture: ADMINISTRATOR ONLY, DISPOSABLE CLUSTER.
\set ON_ERROR_STOP on
CREATE ROLE ch078_owner NOLOGIN;
CREATE ROLE ch078_tenant_a LOGIN;
CREATE ROLE ch078_tenant_b LOGIN;
CREATE DATABASE ch078_lab OWNER ch078_owner;
REVOKE ALL ON DATABASE ch078_lab FROM PUBLIC;
GRANT CONNECT ON DATABASE ch078_lab TO ch078_tenant_a,ch078_tenant_b;
\connect ch078_lab
CREATE SCHEMA app AUTHORIZATION ch078_owner;
SET ROLE ch078_owner;
CREATE TABLE app.tenant_orders (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_role text NOT NULL,
 order_ref text NOT NULL,
 secret_note text,
 CONSTRAINT tenant_role_allowed CHECK (tenant_role IN ('ch078_tenant_a','ch078_tenant_b'))
);
INSERT INTO app.tenant_orders(tenant_role,order_ref,secret_note)
VALUES ('ch078_tenant_a','a-001','private-a'),('ch078_tenant_b','b-001','private-b');
ALTER TABLE app.tenant_orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.tenant_orders FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_select ON app.tenant_orders FOR SELECT
 TO ch078_tenant_a,ch078_tenant_b USING (tenant_role=current_user);
CREATE POLICY tenant_insert ON app.tenant_orders FOR INSERT
 TO ch078_tenant_a,ch078_tenant_b WITH CHECK (tenant_role=current_user);
CREATE POLICY tenant_update ON app.tenant_orders FOR UPDATE
 TO ch078_tenant_a,ch078_tenant_b
 USING (tenant_role=current_user) WITH CHECK (tenant_role=current_user);
CREATE POLICY tenant_delete ON app.tenant_orders FOR DELETE
 TO ch078_tenant_a,ch078_tenant_b USING (tenant_role=current_user);
RESET ROLE;
GRANT USAGE ON SCHEMA app TO ch078_tenant_a,ch078_tenant_b;
GRANT SELECT(id,tenant_role,order_ref),INSERT(tenant_role,order_ref),
 UPDATE(order_ref,tenant_role),DELETE ON app.tenant_orders
 TO ch078_tenant_a,ch078_tenant_b;
GRANT USAGE ON SEQUENCE app.tenant_orders_id_seq TO ch078_tenant_a,ch078_tenant_b;
